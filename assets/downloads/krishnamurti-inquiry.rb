# Original symbolic reading inspired by J. Krishnamurti.
# These associations are not his teaching or a historical Tarot doctrine.
# Illustrative Ruby DSL: declarations, not an implemented inquiry runtime.
# light = possibility to examine; shadow = possible interference.
# insight = editorial proposition, not a claim of experienced insight.

journey "Freedom and the Movement of Inquiry" do
  inquiry "What sustains conditioning, including my wish to become free?"
  horizon :freedom_from_conditioning
  approach :via_negativa
  numbering :rider_waite_smith

  # I. Persistent perspectives; no required order or spiritual score.
  arcana 0, "The Fool" do
    context  "Meeting the unknown"
    light    "Openness to what is present"
    shadow   "A conclusion arriving before observation"
    insight  "Not knowing need not become another identity"
    question "Can I begin without prescribing what I must discover?"
  end

  arcana 1, "The Magician" do
    context  "Intention and the desire to act"
    light    "Examining the motive of inquiry"
    shadow   "The wish to master or become someone"
    insight  "The intention itself belongs within the inquiry"
    question "Do I seek understanding, approval, security, or control?"
  end

  arcana 2, "The High Priestess" do
    context  "Listening and what remains unarticulated"
    light    "Sensitivity to what was overlooked"
    shadow   "Turning intuition into inner authority"
    insight  "Silence does not certify hidden knowledge"
    question "Can I listen without my explanation arriving first?"
  end

  arcana 3, "The Empress" do
    context  "Sensation, affection, and expression"
    light    "Sensitivity in the encounter with life"
    shadow   "Identification with what I create"
    insight  "Expression can reveal the movement of identification"
    question "What do my creations reveal about my expectations and attachments?"
  end

  arcana 4, "The Emperor" do
    context  "Order, structure, and conditioning"
    light    "Distinguishing practical organization from psychological control"
    shadow   "Rigid images of how life must be"
    insight  "Practical structure need not become psychological authority"
    question "Which rules serve the task, and which protect my self-image?"
  end

  arcana 5, "The Hierophant" do
    context  "Knowledge, tradition, and authority"
    light    "Questioning dependence on a teaching"
    shadow   "Belief accepted as a substitute for seeing"
    insight  "Technical knowledge and psychological dependence are different"
    question "Do I see this for myself, or accept it because an authority says so?"
  end

  arcana 6, "The Lovers" do
    context  "Relationship as a mirror"
    light    "Seeing expectations in relationship"
    shadow   "Possession and images of oneself and another"
    insight  "An image of a person can stand between us"
    question "Am I meeting this person or my representation of them?"
  end

  arcana 7, "The Chariot" do
    context  "Direction, effort, and the controller"
    light    "Noticing the impulse to dominate a reaction"
    shadow   "Division between controller and controlled"
    insight  "The controller may belong to the movement it tries to control"
    question "Who is trying to direct this reaction, and from what memory?"
  end

  arcana 8, "Strength" do
    context  "Resistance and suppression"
    light    "Observing conflict without making it an enemy"
    shadow   "Force used against what one feels"
    insight  "Suppression and understanding are different"
    question "Does my effort to conquer the reaction sustain the conflict?"
  end

  arcana 9, "The Hermit" do
    context  "Self-knowing in everyday life"
    light    "Inquiry without dependence on approval"
    shadow   "Isolation mistaken for freedom"
    insight  "Self-knowing can be encountered in relationship"
    question "Am I observing myself or retreating into an image of independence?"
  end

  arcana 10, "Wheel of Fortune" do
    context  "Repetition and psychological continuity"
    light    "Recognizing a familiar response in a new encounter"
    shadow   "Habit treated as fate"
    insight  "Repetition can become a question rather than a destiny"
    question "What from the past is repeating in this apparently new situation?"
  end

  arcana 11, "Justice" do
    context  "Judgment, comparison, and factual evaluation"
    light    "Distinguishing a fact from condemnation"
    shadow   "Measurement of psychological worth"
    insight  "Responsibility does not require condemning an identity"
    question "Does this judgment clarify the situation or defend an image?"
  end

  arcana 12, "The Hanged Man" do
    context  "The impulse to respond"
    light    "Seeing reaction and the wish to interrupt it"
    shadow   "A prescribed pause treated as a route to insight"
    insight  "A pause can be examined without becoming a technique"
    question "Can I notice the impulse without immediately obeying or suppressing it?"
  end

  arcana 13, "Death" do
    context  "Ending and attachment to continuity"
    light    "Examining the maintenance of a self-image"
    shadow   "Fear of losing the story of oneself"
    insight  "Psychological ending is not erasing practical memory"
    question "What am I protecting by carrying this image of myself forward?"
  end

  arcana 14, "Temperance" do
    context  "Relations within the whole movement"
    light    "Noticing thought, sensation, memory, and action together"
    shadow   "An imposed ideal of balance"
    insight  "Adjusting fragments differs from perceiving their relationship"
    question "How are these aspects participating in the same reaction?"
  end

  arcana 15, "The Devil" do
    context  "Attachment, desire, and dependence"
    light    "Seeing attachment and fear together"
    shadow   "Security sought through possession"
    insight  "Condemning desire differs from understanding its movement"
    question "What do I depend on that I am afraid to lose?"
  end

  arcana 16, "The Tower" do
    context  "A challenged image of security"
    light    "Examining what contradiction exposes"
    shadow   "Replacing a broken certainty with another"
    insight  "A crisis is not a required path to freedom"
    question "Is a fact being threatened, or my representation of it?"
  end

  arcana 17, "The Star" do
    context  "Possibility and projected hope"
    light    "Openness without a promised destination"
    shadow   "Future salvation replacing present observation"
    insight  "Hope is not evidence of freedom"
    question "Can I remain open without demanding a reassuring future?"
  end

  arcana 18, "The Moon" do
    context  "Fear, interpretation, and projection"
    light    "Distinguishing what happens from what is anticipated"
    shadow   "Past experience projected as inevitable future"
    insight  "Psychological projection and concrete danger are different"
    question "What is present, and what am I imagining will happen?"
  end

  arcana 19, "The Sun" do
    context  "Clarity and the limits of description"
    light    "Examining whether words help observation"
    shadow   "Confidence mistaken for direct perception"
    insight  "The description does not replace the encounter"
    question "Is this explanation helping me see, or standing in for seeing?"
  end

  arcana 20, "Judgement" do
    context  "Awakening to the movement of relationship"
    light    "Questioning the division between observer and observed"
    shadow   "Condemnation disguised as awakening"
    insight  "The observer is also open to investigation"
    question "Is the observer of this reaction separate from its thought and memory?"
  end

  arcana 21, "The World" do
    context  "The whole and renewed openness"
    light    "Seeing relationships without claiming finality"
    shadow   "The identity of one who has arrived"
    insight  "An account of the whole can still become a limiting image"
    question "Can understanding remain open without becoming a new authority?"
  end

  # II. Reference the same three paths as the article.
  # These lists preserve the editorial sequences; they do not prescribe
  # psychological progression or methods of liberation.
  origin :the_fool, arcana: 0

  path :osiris do
    meaning :transformation
    traverse 1, 4, 7, 10, 13, 16, 19
    question "What maintains the structure I am trying to change?"
  end

  path :thoth_sopdet do
    meaning :awakening
    traverse 2, 5, 8, 11, 14, 17, 20
    question "What becomes visible when authority and judgment are examined?"
  end

  path :horus do
    meaning :experience
    traverse 3, 6, 9, 12, 15, 18, 21
    question "What does relationship reveal about the movement of my mind?"
  end

  interweave :osiris, :thoth_sopdet, :horus

  # III. Attention is a question throughout, not a numbered achievement.
  attention :throughout do
    observe :what_is
    include :motive, :memory, :image, :reaction, :observer
    question "Can this be observed without justification or condemnation?"
    distinguish :practical_knowledge, :psychological_authority
    remain_open_to :questioning_the_map_itself
  end

  inquiry_movement :non_linear do
    revisit :any_arcana
    examine :the_intention_itself
    allow :pause, :unresolved_questions
    preserve :accounts, :sources, :limitations
    distinguish :recorded_account, :living_perception
    promise_no :programmed_insight, :guaranteed_freedom
  end

  # IV. 22 is the symbolic return event, not another card.
  # Use cycle: return is a Ruby keyword, not a suitable DSL method name.
  cycle from: 21, to: 0, event: 22 do
    carry :the_record_with_its_limits
    question "Has this understanding become another conditioning image?"
    renew :inquiry
    impose_no :required_sequence, :final_identity
  end
end
